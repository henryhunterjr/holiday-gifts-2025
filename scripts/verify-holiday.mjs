import { chromium } from 'playwright-core';
import fs from 'node:fs/promises';
const url=process.argv[2] || 'http://127.0.0.1:5180/';
const out=process.argv[3] || 'qa/holiday';
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--disable-features=PointerLockOptions']});
const context=await browser.newContext({viewport:{width:1440,height:1000},permissions:['clipboard-read','clipboard-write']});
await context.addInitScript(()=>{Element.prototype.requestPointerLock=()=>{}; Element.prototype.setPointerCapture=()=>{};});
const page=await context.newPage();
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
await page.goto(url,{waitUntil:'networkidle'});
await page.screenshot({path:out+'/desktop-hero.jpg',quality:85});
await page.locator('#grain-to-gift').scrollIntoViewIfNeeded();
await page.screenshot({path:out+'/desktop-partners.jpg',quality:85});
await page.getByRole('button',{name:'Copy Grand Teton code crustandcrumb'}).click();
if(await page.evaluate(()=>navigator.clipboard.readText())!=='crustandcrumb')throw Error('copy code failed');
await page.locator('#top6').scrollIntoViewIfNeeded();
await page.screenshot({path:out+'/desktop-edit.jpg',quality:85});
await page.getByRole('button',{name:'View all 41 gifts'}).click();
await page.evaluate(async()=>{for(const i of document.images){i.loading='eager';} await Promise.all([...document.images].map(i=>i.decode().catch(()=>{})));});
const images=await page.locator('img').evaluateAll(imgs=>imgs.map(i=>({src:i.currentSrc,alt:i.alt,width:i.naturalWidth}))); 
const failures=images.filter(i=>!i.width);
if(failures.length)throw Error('image failures: '+JSON.stringify(failures));
const fallback=await page.locator('.holiday-photo-fallback').count();
if(fallback)throw Error('hidden product image failures: '+JSON.stringify(await page.locator('.holiday-photo-fallback').allTextContents()));
await page.getByRole('searchbox').fill('Goldie');
if(await page.locator('#browse .holiday-product-card').count()!==1)throw Error('search failed');
await page.getByRole('button',{name:'Save Goldie Starter Warmer to your gift list'}).click();
await page.getByRole('button',{name:'Saved gifts, 1 saved'}).click();
if(!await page.getByRole('dialog').isVisible())throw Error('saved list failed');
await page.keyboard.press('Escape');
await page.getByRole('button',{name:'Clear all filters'}).click();
await page.getByRole('button',{name:'Help me choose'}).click();
await page.screenshot({path:out+'/gift-finder.jpg',quality:85});
const quiz=await page.getByRole('dialog').innerText();
for(const choice of ['A new baker','Under $25','Starter Care','Stocking stuffer']) await page.getByRole('button',{name:choice,exact:true}).click();
await page.getByRole('dialog').locator('a[target="_blank"]').first().waitFor();
const results=await page.getByRole('dialog').innerText();
await page.screenshot({path:out+'/gift-finder-results.jpg',quality:85});
await page.keyboard.press('Escape');
await page.reload({waitUntil:'networkidle'});
if(!await page.getByRole('button',{name:'Saved gifts, 1 saved'}).isVisible())throw Error('saved gift persistence failed');
await page.getByRole('group',{name:'Category filters'}).getByRole('button',{name:'Starter Care',exact:true}).click();
await page.getByRole('group',{name:'Price filters'}).getByRole('button',{name:'Under $25',exact:true}).click();
if(!await page.locator('#browse .holiday-product-card').count())throw Error('combined filters failed');
const widths=[];
for(const width of [360,390,430,768,1440]){
 await page.setViewportSize({width,height:844}); await page.goto(url,{waitUntil:'networkidle'});
 const overflow=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth})); widths.push(overflow);
 if(overflow.scroll>width)throw Error('horizontal overflow '+JSON.stringify(overflow));
 if(width===390){await page.screenshot({path:out+'/mobile-hero.jpg',quality:85}); await page.locator('#grain-to-gift').scrollIntoViewIfNeeded();await page.screenshot({path:out+'/mobile-partners.jpg',quality:85});await page.locator('#top6').scrollIntoViewIfNeeded();await page.screenshot({path:out+'/mobile-edit.jpg',quality:85});}
}
await page.emulateMedia({reducedMotion:'reduce'});await page.goto(url,{waitUntil:'networkidle'});
const motion=await page.locator('.hero-main-photo').evaluate(e=>getComputedStyle(e).animationName);
if(motion!=='none')throw Error('reduced motion failed');
await page.screenshot({path:out+'/reduced-motion.jpg',quality:85});
await fs.writeFile(out+'/report.json',JSON.stringify({url,images:images.length,failures,fallback,widths,quiz,results,errors,motion,checks:['image decoding','copy partner code','expanded catalog','search','combined category/budget filters','saved list and reload persistence','Gift Finder completion','reduced motion']},null,2));
console.log(JSON.stringify({images:images.length,widths,errors,motion}));
await browser.close();
